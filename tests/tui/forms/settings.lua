-- A long settings form for tests/tui/journeys.py: thirty fields of every kind, so the form scrolls
-- and every awkward case is on it. It stands in for nodo-fixture-forms until that lands.
--   SMTP port, Keep logs for, Backup hour and Requests per minute: optional ints with no default,
--     which must never block saving the other fields while empty
--   Contact email, Greeting and Admin notes: strings with the package's own validators
--   Log level, Mail delivery, Colour theme, Display currency and Language: enums
--   API token, Admin password, Webhook signing key and Debug token: secrets
-- Labels are all different and none is part of another or of any help text, so a test can find
-- each on screen by its label alone.
return { api_version = 1, settings = {
  { name = "instance_name", type = "string", label = "Instance name", default = "forms",
    help = "Shown at the top of every page." },
  { name = "log_level", type = "enum", label = "Log level", choices = { "error", "warn", "info", "debug" },
    default = "info", help = "How much it writes down." },
  { name = "workers", type = "int", label = "Worker threads", default = 2, min = 1, max = 16,
    help = "Requests handled at once." },
  { name = "smtp_port", type = "int", label = "SMTP port", min = 1, max = 65535,
    help = "Leave empty to use the usual one." },
  { name = "smtp_host", type = "string", label = "Mail server", help = "Leave empty to send no mail." },
  { name = "contact_email", type = "string", label = "Contact email", help = "Where people can write to.",
    validate = function(v) return v == "" or nodo.matches(v, "^[^@ ]+@[^@ ]+$"), "must look like name@example.com" end },
  { name = "mail_mode", type = "enum", label = "Mail delivery", choices = { "off", "smtp", "sendmail" },
    default = "off", help = "How messages leave the device." },
  { name = "api_token", type = "secret", label = "API token", help = "For the remote API, if used." },
  { name = "admin_secret", type = "secret", label = "Admin password", help = "At least 16 characters.",
    validate = function(v) return #v >= 16, "must be at least 16 characters" end },
  { name = "public_url", type = "url", label = "Public address", help = "Where visitors find it." },
  { name = "allow_signups", type = "bool", label = "Allow sign-ups", default = false,
    help = "Let visitors make accounts." },
  { name = "theme", type = "enum", label = "Colour theme", choices = { "light", "dark", "auto" },
    default = "auto", help = "Follows the browser when automatic." },
  { name = "max_upload_mib", type = "int", label = "Largest upload (MiB)", default = 10, min = 1, max = 1024,
    help = "Bigger files are refused." },
  { name = "retention_days", type = "int", label = "Keep logs for (days)", min = 1, max = 3650,
    help = "Leave empty to keep them forever." },
  { name = "webhook_url", type = "url", label = "Webhook target", help = "Called on every new order." },
  { name = "webhook_secret", type = "secret", label = "Webhook signing key", help = "Signs each call." },
  { name = "greeting", type = "string", label = "Greeting", default = "hello", help = "Twelve characters at most.",
    validate = function(v) return #v <= 12, "must be 12 characters or fewer" end },
  { name = "footer_text", type = "string", label = "Footer text", help = "Small print under each page." },
  { name = "currency", type = "enum", label = "Display currency", choices = { "XMR", "USD", "EUR" },
    default = "XMR", help = "Prices are converted for show only." },
  { name = "payout", type = "monero-address", label = "Payout wallet", help = "Payments go here." },
  { name = "timezone", type = "string", label = "Time zone", default = "UTC", help = "For dates in emails." },
  { name = "cache_mib", type = "int", label = "Cache size (MiB)", default = 64, min = 8, max = 4096,
    help = "Memory kept for pages." },
  { name = "backup_hour", type = "int", label = "Backup hour", min = 0, max = 23,
    help = "Leave empty for no nightly copy." },
  { name = "maintenance", type = "bool", label = "Maintenance mode", default = false,
    help = "Visitors see a notice instead." },
  { name = "language", type = "enum", label = "Language", choices = { "en", "de", "fr", "es" }, default = "en",
    help = "For visitors who have not chosen." },
  { name = "support_url", type = "url", label = "Support page", help = "Linked from the footer." },
  { name = "motd", type = "string", label = "Message of the day", help = "Shown once per visit." },
  { name = "rate_limit", type = "int", label = "Requests per minute", min = 1, max = 100000,
    help = "Leave empty for no limit." },
  { name = "debug_token", type = "secret", label = "Debug token", help = "Turns on the debug page." },
  { name = "notes", type = "string", label = "Admin notes", help = "Forty characters at most.",
    validate = function(v) return #v <= 40, "must be 40 characters or fewer" end },
} }
